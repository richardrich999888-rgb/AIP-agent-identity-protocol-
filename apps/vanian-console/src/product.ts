export const pretty = (s: string) =>
  ({
    app: "Application",
    scope: "Scope",
    kind: "Actor type",
    risk: "Risk",
    state: "Status",
    group: "Group",
    costKind: "Cost basis",
    verification: "Signature",
    day: "Observation date",
    priority: "Alert priority",
  })[s] || s.replace(/([A-Z])/g, " $1").replace(/^./, (a) => a.toUpperCase());
export const field = (
  r: import("./types").Entry,
  k: string,
): string | number | boolean =>
  k === "name" ||
  k === "id" ||
  k === "at" ||
  k === "group" ||
  k === "source" ||
  k === "state"
    ? r[k]
    : (r.fields[k] ?? "");
