//! Capability artifact: a typed, versioned, content-addressed procedure.
//!
//! A capability is *data*, never code. Its procedure is written in the
//! restricted language of [`super::expr`] over inputs extracted by the
//! runtime's reviewed quantity parser ([`super::quantity`]). It carries its
//! applicability conditions, required permissions, dependency bindings,
//! evidence references, tests and counterexamples.
//!
//! What an artifact cannot do, by construction:
//! - grant itself permissions: `required` is a *requirement* checked against
//!   the caller; there is no field that confers authority;
//! - invoke tools, models or IO: the language has no calls;
//! - certify itself: validation counts only tests whose `source` is `Expert`
//!   and whose author differs from the proposer (see `validate`).

use std::collections::BTreeMap;

use serde::{Deserialize, Serialize};

use super::evidence::{values_from_record, EvidencePolicy, MeasurementRecord};
use super::expr::{
    eval, eval_cond, parse_cond, parse_expr, vars_cond, vars_expr, Cond, Expr, ExprError,
};
use super::quantity::{cued_numbers, find_term, quantities, Kind, MAX_TEXT_CHARS};

/// Limits on artifact size (bounded validation and execution cost).
pub const MAX_INPUTS: usize = 12;
pub const MAX_STEPS: usize = 48;
pub const MAX_TERMS: usize = 32;

/// One extracted input.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct InputSpec {
    /// Variable name used by expressions (`[a-z_][a-z0-9_]*`).
    pub name: String,
    pub kind: Kind,
    /// Cue words for `Kind::Cued` inputs (e.g. "PI", "polarization index").
    #[serde(default)]
    pub cues: Vec<String>,
}

/// When the capability applies to a request at all.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Applicability {
    /// At least one of these terms must appear (word-bounded, case-insensitive).
    pub any_terms: Vec<String>,
    /// At least this many declared inputs must be found in the text.
    pub min_inputs_present: usize,
}

/// A text guard: if any term appears, the outcome is fixed.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct TextGuard {
    pub any_terms: Vec<String>,
    pub outcome: String,
}

/// A numeric guard: evaluated only when every variable it uses is present.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct NumericGuard {
    pub when: String,
    pub outcome: String,
}

/// A derived quantity.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Derive {
    pub name: String,
    pub expr: String,
}

/// An ordered decision rule.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Rule {
    pub when: String,
    pub outcome: String,
}

/// The procedure body.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Procedure {
    pub inputs: Vec<InputSpec>,
    #[serde(default)]
    pub text_guards: Vec<TextGuard>,
    #[serde(default)]
    pub numeric_guards: Vec<NumericGuard>,
    pub missing_input_outcome: String,
    #[serde(default)]
    pub derive: Vec<Derive>,
    pub rules: Vec<Rule>,
    pub default_outcome: String,
}

/// Who wrote a test case.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum TestSource {
    /// Written or confirmed by a named domain expert (counts toward validation).
    Expert,
    /// Generated by the proposer or a model (never counts toward validation).
    Generated,
}

/// One validation case.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct TestCase {
    pub id: String,
    pub text: String,
    pub expected: String,
    pub source: TestSource,
    /// Principal id of the author (proposer ≠ expert is enforced).
    pub author: String,
    /// A counterexample is a case designed to break a naive procedure
    /// (boundary, out-of-scope, missing input).
    #[serde(default)]
    pub counterexample: bool,
}

/// Requirements on the *caller* (not grants).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Required {
    pub tenant: String,
    /// "public" | "internal" | "restricted" (minimum clearance).
    pub min_clearance: String,
    pub security_domain: String,
}

/// What the capability's validity depends on.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Dependencies {
    /// SHA-256 (hex) of each evidence document version the procedure encodes.
    pub knowledge: BTreeMap<String, String>,
    pub policy_version: String,
    /// `None`: execution is model-independent (deterministic extraction).
    /// `Some(sha)`: execution calls this model; a model change requires
    /// compatibility re-validation before reuse.
    pub execution_model_sha256: Option<String>,
}

/// The complete artifact. Its content hash is its identity.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Capability {
    pub id: String,
    pub version: u32,
    pub intended_task: String,
    pub outcomes: Vec<String>,
    pub applicability: Applicability,
    pub procedure: Procedure,
    pub required: Required,
    pub dependencies: Dependencies,
    /// Demonstration / document ids this capability was built from.
    pub evidence_refs: Vec<String>,
    pub failure_conditions: Vec<String>,
    pub tests: Vec<TestCase>,
    /// Who proposed it: principal id, or `model:<sha256>` for a model proposal.
    pub proposed_by: String,
    /// Where input numbers may come from (S1). Omitted when `Text`, so the
    /// content hash of every pre-existing capability is unchanged.
    #[serde(default, skip_serializing_if = "EvidencePolicy::is_text")]
    pub evidence: EvidencePolicy,
}

#[derive(Debug, Clone, PartialEq)]
pub enum ArtifactError {
    Limit(&'static str),
    BadName(String),
    UnknownOutcome(String),
    Expr { field: String, err: ExprError },
    UndefinedVariable { field: String, var: String },
    Empty(&'static str),
}

fn valid_name(n: &str) -> bool {
    let mut c = n.chars();
    matches!(c.next(), Some(ch) if ch.is_ascii_lowercase() || ch == '_')
        && c.all(|ch| ch.is_ascii_lowercase() || ch.is_ascii_digit() || ch == '_')
        && n.len() <= 32
        && !matches!(n, "and" | "or")
}

/// A compiled procedure, ready to execute.
#[derive(Debug, Clone)]
pub struct Compiled {
    numeric_guards: Vec<(Cond, Vec<String>, String)>,
    derive: Vec<(String, Expr)>,
    rules: Vec<(Cond, String)>,
}

/// Result of running a capability on one request.
#[derive(Debug, Clone, PartialEq)]
pub enum Execution {
    /// The capability does not apply; the controller must choose another strategy.
    NotApplicable,
    /// An input was found more than once with different values.
    Ambiguous { input: String },
    /// A decision, with the inputs and derived values that produced it.
    Decided {
        outcome: String,
        values: BTreeMap<String, f64>,
        /// Index of the rule/guard that fired, for audit.
        step: String,
    },
    /// Evaluation error (division by zero, non-finite…). Never guessed past.
    Failed(String),
    /// The capability decides only on a signed measurement record (S1) and
    /// none was supplied; text numbers are never used instead.
    EvidenceRequired,
}

impl Capability {
    /// Canonical content hash (hex SHA-256 of the canonical JSON).
    pub fn content_hash(&self) -> String {
        // serde_json writes struct fields in declaration order and BTreeMap
        // keys sorted, so this serialization is canonical for this type.
        let b = serde_json::to_vec(self).unwrap_or_default();
        hex::encode(aip_crypto::sha256(&b))
    }

    /// Static checks + compilation. Every variable must be an input or an
    /// earlier derived value; every outcome must be declared.
    pub fn compile(&self) -> Result<Compiled, ArtifactError> {
        let p = &self.procedure;
        if self.outcomes.is_empty() {
            return Err(ArtifactError::Empty("outcomes"));
        }
        if p.inputs.is_empty() || p.inputs.len() > MAX_INPUTS {
            return Err(ArtifactError::Limit("inputs"));
        }
        if p.rules.len() + p.derive.len() + p.numeric_guards.len() + p.text_guards.len() > MAX_STEPS
        {
            return Err(ArtifactError::Limit("steps"));
        }
        let terms = self.applicability.any_terms.len()
            + p.text_guards
                .iter()
                .map(|g| g.any_terms.len())
                .sum::<usize>();
        if terms > MAX_TERMS || self.applicability.any_terms.is_empty() {
            return Err(ArtifactError::Limit("terms"));
        }
        let known_outcome = |o: &str| -> Result<(), ArtifactError> {
            if self.outcomes.iter().any(|x| x == o) {
                Ok(())
            } else {
                Err(ArtifactError::UnknownOutcome(o.into()))
            }
        };
        let mut defined: Vec<String> = Vec::new();
        for i in &p.inputs {
            if !valid_name(&i.name) || defined.contains(&i.name) {
                return Err(ArtifactError::BadName(i.name.clone()));
            }
            if i.kind == Kind::Cued && i.cues.is_empty() {
                return Err(ArtifactError::Empty("cues"));
            }
            defined.push(i.name.clone());
        }
        let check_vars =
            |field: &str, vars: Vec<String>, defined: &[String]| -> Result<(), ArtifactError> {
                for v in vars {
                    if !defined.contains(&v) {
                        return Err(ArtifactError::UndefinedVariable {
                            field: field.into(),
                            var: v,
                        });
                    }
                }
                Ok(())
            };
        let ex = |field: String| {
            move |err| ArtifactError::Expr {
                field: field.clone(),
                err,
            }
        };
        for g in &p.text_guards {
            known_outcome(&g.outcome)?;
        }
        let mut numeric_guards = vec![];
        for (k, g) in p.numeric_guards.iter().enumerate() {
            let f = format!("numeric_guards[{k}]");
            let c = parse_cond(&g.when).map_err(ex(f.clone()))?;
            let vars = vars_cond(&c);
            check_vars(&f, vars.clone(), &defined)?;
            known_outcome(&g.outcome)?;
            numeric_guards.push((c, vars, g.outcome.clone()));
        }
        known_outcome(&p.missing_input_outcome)?;
        known_outcome(&p.default_outcome)?;
        let mut derive = vec![];
        for (k, d) in p.derive.iter().enumerate() {
            let f = format!("derive[{k}]");
            if !valid_name(&d.name) || defined.contains(&d.name) {
                return Err(ArtifactError::BadName(d.name.clone()));
            }
            let e = parse_expr(&d.expr).map_err(ex(f.clone()))?;
            let mut vars = vec![];
            vars_expr(&e, &mut vars);
            check_vars(&f, vars, &defined)?;
            defined.push(d.name.clone());
            derive.push((d.name.clone(), e));
        }
        let mut rules = vec![];
        for (k, r) in p.rules.iter().enumerate() {
            let f = format!("rules[{k}]");
            let c = parse_cond(&r.when).map_err(ex(f.clone()))?;
            check_vars(&f, vars_cond(&c), &defined)?;
            known_outcome(&r.outcome)?;
            rules.push((c, r.outcome.clone()));
        }
        Ok(Compiled {
            numeric_guards,
            derive,
            rules,
        })
    }

    /// Extract this capability's inputs from text. `Err(name)` = ambiguous.
    pub fn extract(&self, text: &str) -> Result<BTreeMap<String, f64>, String> {
        let typed = quantities(text);
        let mut out = BTreeMap::new();
        for i in &self.procedure.inputs {
            let cands: Vec<f64> = if i.kind == Kind::Cued {
                cued_numbers(text, &i.cues)
                    .into_iter()
                    .map(|q| q.value)
                    .collect()
            } else {
                typed
                    .iter()
                    .filter(|q| q.kind == i.kind)
                    .map(|q| q.value)
                    .collect()
            };
            let mut uniq: Vec<f64> = vec![];
            for v in cands {
                if !uniq.contains(&v) {
                    uniq.push(v);
                }
            }
            match uniq.len() {
                0 => {}
                1 => {
                    out.insert(i.name.clone(), uniq[0]);
                }
                _ => return Err(i.name.clone()),
            }
        }
        Ok(out)
    }

    fn has_any(text_lower: &[char], terms: &[String]) -> bool {
        terms.iter().any(|t| !find_term(text_lower, t).is_empty())
    }

    /// Strength of match for routing among several applicable capabilities
    /// (S2, strongest-fit router): number of this capability's inputs found
    /// in the text, plus one if a topic term (an applicability term that is
    /// not a unit spelling) occurs. Unit spellings are shared by every
    /// capability on the same physics and so cannot discriminate between them
    /// (round-1 collision experiment: 4/130 → 117/130 decided correctly).
    pub fn fit(&self, text: &str) -> u32 {
        let lower: Vec<char> = text
            .chars()
            .take(MAX_TEXT_CHARS)
            .flat_map(|c| c.to_lowercase())
            .collect();
        let topic: Vec<String> = self
            .applicability
            .any_terms
            .iter()
            .filter(|t| quantities(&format!("1 {t}")).is_empty())
            .cloned()
            .collect();
        let inputs = match self.extract(text) {
            Ok(m) => m.len(),
            Err(_) => self.procedure.inputs.len(),
        };
        inputs as u32 + u32::from(Self::has_any(&lower, &topic))
    }

    /// Does the capability apply to this text? (No decision is made.)
    pub fn applies(&self, text: &str) -> bool {
        let lower: Vec<char> = text
            .chars()
            .take(MAX_TEXT_CHARS)
            .flat_map(|c| c.to_lowercase())
            .collect();
        if !Self::has_any(&lower, &self.applicability.any_terms) {
            return false;
        }
        let found = match self.extract(text) {
            Ok(m) => m.len(),
            Err(_) => self.procedure.inputs.len(), // ambiguity is reported by execute
        };
        found >= self.applicability.min_inputs_present
    }

    /// Run the compiled procedure. Order: applicability → text guards →
    /// numeric guards (only when their variables are present) → missing
    /// inputs → derived values → rules → default.
    pub fn execute(&self, c: &Compiled, text: &str) -> Execution {
        if !self.applies(text) {
            return Execution::NotApplicable;
        }
        if self.evidence == EvidencePolicy::SignedRecord {
            return Execution::EvidenceRequired;
        }
        let env = match self.extract(text) {
            Ok(m) => m,
            Err(input) => return Execution::Ambiguous { input },
        };
        self.decide(c, text, env)
    }

    /// Run the procedure on numbers in text whatever the evidence policy.
    /// Only for text whose numbers are vouched for by a signature other than
    /// an instrument's: cases in an expert-signed validation suite, and
    /// independently verified experience under review. Never on requests.
    pub fn execute_attested_text(&self, c: &Compiled, text: &str) -> Execution {
        if !self.applies(text) {
            return Execution::NotApplicable;
        }
        match self.extract(text) {
            Ok(env) => self.decide(c, text, env),
            Err(input) => Execution::Ambiguous { input },
        }
    }

    /// S1: run on a record the caller has ALREADY verified
    /// (`MeasurementRecord::verify`). The text selects and scope-checks;
    /// every number comes from the record. Applicability: a topic or cue
    /// term in the text and at least `min_inputs_present` inputs in the record.
    pub fn execute_with_record(
        &self,
        c: &Compiled,
        text: &str,
        rec: &MeasurementRecord,
    ) -> Execution {
        let env = match values_from_record(self, rec) {
            Ok(m) => m,
            Err(super::evidence::RecordError::Conflict(input)) => {
                return Execution::Ambiguous { input }
            }
            Err(e) => return Execution::Failed(format!("record: {e:?}")),
        };
        let lower: Vec<char> = text
            .chars()
            .take(MAX_TEXT_CHARS)
            .flat_map(|c| c.to_lowercase())
            .collect();
        if !Self::has_any(&lower, &self.applicability.any_terms)
            || env.len() < self.applicability.min_inputs_present
        {
            return Execution::NotApplicable;
        }
        self.decide(c, text, env)
    }

    /// Guards, missing inputs, derived values, rules, default — on `env`.
    fn decide(&self, c: &Compiled, text: &str, mut env: BTreeMap<String, f64>) -> Execution {
        let lower: Vec<char> = text
            .chars()
            .take(MAX_TEXT_CHARS)
            .flat_map(|c| c.to_lowercase())
            .collect();
        for (k, g) in self.procedure.text_guards.iter().enumerate() {
            if Self::has_any(&lower, &g.any_terms) {
                return Execution::Decided {
                    outcome: g.outcome.clone(),
                    values: env,
                    step: format!("text_guards[{k}]"),
                };
            }
        }
        for (k, (cond, vars, outcome)) in c.numeric_guards.iter().enumerate() {
            if vars.iter().all(|v| env.contains_key(v)) {
                match eval_cond(cond, &env) {
                    Ok(true) => {
                        return Execution::Decided {
                            outcome: outcome.clone(),
                            values: env,
                            step: format!("numeric_guards[{k}]"),
                        }
                    }
                    Ok(false) => {}
                    Err(e) => return Execution::Failed(format!("numeric_guards[{k}]: {e:?}")),
                }
            }
        }
        if self
            .procedure
            .inputs
            .iter()
            .any(|i| !env.contains_key(&i.name))
        {
            return Execution::Decided {
                outcome: self.procedure.missing_input_outcome.clone(),
                values: env,
                step: "missing_input".into(),
            };
        }
        for (name, e) in &c.derive {
            match eval(e, &env) {
                Ok(v) => {
                    env.insert(name.clone(), v);
                }
                Err(err) => return Execution::Failed(format!("derive {name}: {err:?}")),
            }
        }
        for (k, (cond, outcome)) in c.rules.iter().enumerate() {
            match eval_cond(cond, &env) {
                Ok(true) => {
                    return Execution::Decided {
                        outcome: outcome.clone(),
                        values: env,
                        step: format!("rules[{k}]"),
                    }
                }
                Ok(false) => {}
                Err(e) => return Execution::Failed(format!("rules[{k}]: {e:?}")),
            }
        }
        Execution::Decided {
            outcome: self.procedure.default_outcome.clone(),
            values: env,
            step: "default".into(),
        }
    }
}
