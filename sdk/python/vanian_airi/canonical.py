"""Prefix-free canonical encoding — byte-identical to ``aip_types::canonical``.

Every variable-length field carries a u32 little-endian length prefix, every
optional field carries an explicit presence byte, and every signed payload
opens with a domain tag. That is what makes a signature commit to exactly
one interpretation of the bytes.

This module is a port, not a reimplementation with liberties. The parity
tests in ``tests/test_canonical_parity.py`` compare its output against
vectors generated by the Rust encoder; if the two ever diverge, a Python
agent's events stop verifying in Rust and the divergence must be a build
failure, not a runtime surprise.
"""

from __future__ import annotations

import struct
from typing import Optional

__all__ = [
    "put_domain",
    "put_u8",
    "put_u16",
    "put_u32",
    "put_u64",
    "put_bytes",
    "put_str",
    "put_opt_str",
    "put_opt_u64",
    "put_opt_bytes",
    "put_opt_digest",
]

_U32_MAX = 0xFFFF_FFFF


def put_u8(buf: bytearray, v: int) -> None:
    if not 0 <= v <= 0xFF:
        raise ValueError(f"u8 out of range: {v}")
    buf.append(v)


def put_u16(buf: bytearray, v: int) -> None:
    if not 0 <= v <= 0xFFFF:
        raise ValueError(f"u16 out of range: {v}")
    buf.extend(struct.pack("<H", v))


def put_u32(buf: bytearray, v: int) -> None:
    if not 0 <= v <= _U32_MAX:
        raise ValueError(f"u32 out of range: {v}")
    buf.extend(struct.pack("<I", v))


def put_u64(buf: bytearray, v: int) -> None:
    if not 0 <= v <= 0xFFFF_FFFF_FFFF_FFFF:
        raise ValueError(f"u64 out of range: {v}")
    buf.extend(struct.pack("<Q", v))


def put_bytes(buf: bytearray, data: bytes) -> None:
    """Length-prefixed byte string.

    The length is cast to u32 in Rust; here an oversized value raises rather
    than silently truncating, because a truncated length prefix is a
    signature-forgery primitive.
    """
    if len(data) > _U32_MAX:
        raise ValueError("field exceeds u32 length prefix")
    put_u32(buf, len(data))
    buf.extend(data)


def put_str(buf: bytearray, s: str) -> None:
    put_bytes(buf, s.encode("utf-8"))


def put_domain(buf: bytearray, domain: str) -> None:
    """Write the domain-separation tag that opens a signed payload."""
    put_str(buf, domain)


def put_opt_str(buf: bytearray, s: Optional[str]) -> None:
    if s is None:
        put_u8(buf, 0)
    else:
        put_u8(buf, 1)
        put_str(buf, s)


def put_opt_u64(buf: bytearray, v: Optional[int]) -> None:
    if v is None:
        put_u8(buf, 0)
    else:
        put_u8(buf, 1)
        put_u64(buf, v)


def put_opt_bytes(buf: bytearray, v: Optional[bytes], expect_len: int) -> None:
    """Optional fixed-width field: presence byte, then the raw bytes.

    ``expect_len`` is enforced. A fixed-width field written at the wrong
    length would shift every following field and change the meaning of the
    signed bytes.
    """
    if v is None:
        put_u8(buf, 0)
    else:
        if len(v) != expect_len:
            raise ValueError(f"expected {expect_len} bytes, got {len(v)}")
        put_u8(buf, 1)
        buf.extend(v)


def put_opt_digest(buf: bytearray, v: Optional[bytes]) -> None:
    """Optional 32-byte digest, length-prefixed to match the Rust encoder.

    Note the asymmetry with :func:`put_opt_bytes`: Rust writes digests inside
    payload bodies with ``put_bytes`` (length-prefixed), and fixed identifier
    fields raw. This function matches the former.
    """
    if v is None:
        put_u8(buf, 0)
    else:
        if len(v) != 32:
            raise ValueError(f"digest must be 32 bytes, got {len(v)}")
        put_u8(buf, 1)
        put_bytes(buf, v)
