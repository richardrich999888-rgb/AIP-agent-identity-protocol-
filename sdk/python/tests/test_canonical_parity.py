"""Cross-language parity: the Python encoder must equal the Rust encoder.

# Why this is the most important test in the SDK

The Python SDK reimplements ``aip_types::canonical`` and
``AiriEvent::signing_preimage``. If the two ever disagree by one byte, one of
two things happens, and both are bad:

* the Rust verifier refuses every event a Python agent produces, which is
  loud and merely breaks the deployment; or
* the two produce *different preimages for the same logical event*, which is
  quiet. The signature then commits to something other than what the Python
  side believes it signed, and the entire binding argument collapses.

``tests/parity_vectors.json`` is generated by the Rust test
``aip-airi --test parity_vectors -- --ignored``. It is the contract. A
divergence here is a build failure, not a runtime surprise.
"""

from __future__ import annotations

import json
import pathlib
import sys
import unittest

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))

from vanian_airi import commit_bytes  # noqa: E402
from vanian_airi.events import (  # noqa: E402
    AiriEvent,
    AiriEventKind,
    Completion,
    ContextPropagationBody,
    FrameworkIdentity,
    ModelProvenance,
    ProcessInstance,
    PropagationBoundary,
    ReportedOutcome,
    RuntimeBinding,
    SubprocessReport,
    ToolInvocation,
    ToolReport,
)

VECTORS = json.loads((pathlib.Path(__file__).parent / "parity_vectors.json").read_text())

AGENT = "aip1testagent"
EXEC_A = bytes([0xA1] * 16)
EXEC_B = bytes([0xB2] * 16)
DECISION_A = bytes([0xD1] * 16)
FRAMEWORK = FrameworkIdentity("langgraph", "0.2.0", "vanian-airi-adapter/1")
EMITTED_AT = 1_700_000_000_000


def base(kind: AiriEventKind, payload: object, **over: object) -> AiriEvent:
    """The skeleton the Rust vector generator uses, with per-case overrides."""
    fields: dict[str, object] = dict(
        kind=kind,
        agent_id=AGENT,
        execution_id=EXEC_A,
        sequence=0,
        prev_event_hash=bytes(32),
        emitted_at_ms=EMITTED_AT,
        framework=FRAMEWORK,
        payload=payload,
        parent_execution_id=None,
        decision_id=None,
        runtime_binding=None,
    )
    fields.update(over)
    return AiriEvent(**fields)  # type: ignore[arg-type]


class TestCanonicalParity(unittest.TestCase):
    def assert_matches(self, name: str, event: AiriEvent) -> None:
        expected = VECTORS[name]
        actual = event.signing_preimage().hex()
        if actual != expected:
            # Report the first differing byte: a length-prefix or presence-byte
            # bug shows up as a specific offset, which is the fastest way to
            # find which field drifted.
            a, e = bytes.fromhex(actual), bytes.fromhex(expected)
            off = next(
                (i for i, (x, y) in enumerate(zip(a, e)) if x != y),
                min(len(a), len(e)),
            )
            self.fail(
                f"{name}: preimage diverges from Rust at byte {off}\n"
                f"  rust  : ...{e[max(0, off - 8):off + 8].hex()}\n"
                f"  python: ...{a[max(0, off - 8):off + 8].hex()}\n"
                f"  lengths rust={len(e)} python={len(a)}"
            )

    def test_tool_request_minimal(self) -> None:
        self.assert_matches(
            "tool_request_minimal",
            base(
                AiriEventKind.TOOL_INVOCATION_REQUESTED,
                ToolInvocation(
                    tool_id="http.post",
                    action_kind="http.post",
                    parameter_commitment=commit_bytes(b'{"url":"https://x/y"}'),
                ),
            ),
        )

    def test_tool_request_full(self) -> None:
        self.assert_matches(
            "tool_request_full",
            base(
                AiriEventKind.TOOL_INVOCATION_REQUESTED,
                ToolInvocation(
                    tool_id="http.post",
                    action_kind="http.post",
                    parameter_commitment=commit_bytes(b'{"url":"https://x/y"}'),
                    tool_call_id="call_abc",
                    target="payments.internal",
                ),
                decision_id=DECISION_A,
                parent_execution_id=EXEC_B,
                sequence=7,
                prev_event_hash=bytes([0x5A] * 32),
            ),
        )

    def test_model_hosted(self) -> None:
        self.assert_matches(
            "model_hosted",
            base(
                AiriEventKind.MODEL_INVOCATION_REQUESTED,
                ModelProvenance(
                    model_id="claude-opus-5",
                    runtime="hosted-api",
                    inference_request_id="req_123",
                    prompt_commitment=commit_bytes(b"prompt bytes"),
                ),
            ),
        )

    def test_model_local_full(self) -> None:
        self.assert_matches(
            "model_local_full",
            base(
                AiriEventKind.MODEL_INVOCATION_REQUESTED,
                ModelProvenance(
                    model_id="llama-3-70b",
                    runtime="vllm",
                    model_digest=bytes([0x11] * 32),
                    runtime_version="0.6.0",
                    inference_request_id="req_456",
                    prompt_commitment=commit_bytes(b"p"),
                    output_commitment=commit_bytes(b"o"),
                    accelerator="cuda:0",
                ),
            ),
        )

    def test_tool_report(self) -> None:
        self.assert_matches(
            "tool_report",
            base(
                AiriEventKind.TOOL_EXECUTION_REPORTED,
                ToolReport(
                    tool_id="http.post",
                    parameter_commitment=commit_bytes(b"{}"),
                    outcome=ReportedOutcome.SUCCESS,
                    result_commitment=commit_bytes(b'{"ok":true}'),
                    transport_status=200,
                ),
            ),
        )

    def test_subprocess(self) -> None:
        self.assert_matches(
            "subprocess",
            base(
                AiriEventKind.SUBPROCESS_EXECUTION,
                SubprocessReport(
                    program="/bin/sh",
                    argv_commitment=commit_bytes(b'["-c","echo hi"]'),
                    reported_pid=4321,
                ),
            ),
        )

    def test_context_propagated(self) -> None:
        self.assert_matches(
            "context_propagated",
            base(
                AiriEventKind.EXECUTION_CONTEXT_PROPAGATED,
                ContextPropagationBody(
                    boundary=PropagationBoundary.SUBPROCESS,
                    to_execution_id=EXEC_B,
                ),
            ),
        )

    def test_completed(self) -> None:
        self.assert_matches(
            "completed",
            base(
                AiriEventKind.EXECUTION_COMPLETED,
                Completion(outcome=ReportedOutcome.SUCCESS, detail="done"),
            ),
        )

    def test_with_runtime_binding(self) -> None:
        self.assert_matches(
            "with_runtime_binding",
            base(
                AiriEventKind.TOOL_INVOCATION_REQUESTED,
                ToolInvocation(
                    tool_id="http.post",
                    action_kind="http.post",
                    parameter_commitment=commit_bytes(b'{"url":"https://x/y"}'),
                ),
                runtime_binding=RuntimeBinding(
                    agent_id=AGENT,
                    process=ProcessInstance(
                        pid=4321,
                        pid_start_time_ticks=4242,
                        boot_id=bytes([0x7] * 16),
                    ),
                    exe_content_sha256=bytes([0x33] * 32),
                ),
            ),
        )


class TestCommitmentParity(unittest.TestCase):
    def test_commitment_is_not_a_bare_sha256(self) -> None:
        import hashlib

        data = b'{"amount":5}'
        self.assertNotEqual(
            commit_bytes(data),
            hashlib.sha256(data).digest(),
            "a bare SHA-256 would be replayable as a commitment across domains",
        )

    def test_commitment_is_length_prefixed(self) -> None:
        # commit(a) ‖ commit(b) must not equal commit(a ‖ b) — otherwise two
        # separate arguments and one concatenated argument share a commitment.
        self.assertNotEqual(commit_bytes(b"ab"), commit_bytes(b"a") + commit_bytes(b"b"))
        self.assertNotEqual(commit_bytes(b"ab"), commit_bytes(b"a"))


if __name__ == "__main__":
    unittest.main(verbosity=2)
